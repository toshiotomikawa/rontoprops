// Generates responsive WebP variants for every image referenced in
// js/gallery-data.js and writes js/image-manifest.js (a plain global,
// consumed by main.js the same way GALLERY_GROUPS/HIGHLIGHTS are).
// Not committed to git — regenerated on every Vercel build (see
// package.json "build" script) so source photo changes always
// produce fresh variants without a manual step.
import path from 'node:path';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = fileURLToPath(new URL('..', import.meta.url));
const galleryDataFile = path.join(root, 'js', 'gallery-data.js');
const outputDir = path.join(root, 'assets', 'generated');
const manifestFile = path.join(root, 'js', 'image-manifest.js');

const WIDTHS = [320, 480, 768, 1024, 1440];

function loadGalleryData(source) {
  const fn = new Function(`${source}\nreturn { GALLERY_GROUPS, HIGHLIGHTS };`);
  return fn();
}

async function main() {
  const source = await readFile(galleryDataFile, 'utf8');
  const { GALLERY_GROUPS, HIGHLIGHTS } = loadGalleryData(source);

  const allImages = new Set();
  GALLERY_GROUPS.forEach(g => g.images.forEach(i => allImages.add(i)));
  HIGHLIGHTS.forEach(g => g.images.forEach(i => allImages.add(i)));

  await mkdir(outputDir, { recursive: true });

  const manifest = {};

  for (const relSrc of allImages) {
    const inputFile = path.join(root, relSrc);
    const metadata = await sharp(inputFile).metadata();

    if (!metadata.width || !metadata.height) {
      throw new Error(`Could not read dimensions for ${inputFile}`);
    }

    let widths = WIDTHS.filter(w => w <= metadata.width);
    if (!widths.includes(metadata.width)) widths.push(metadata.width);
    widths = [...new Set(widths)].sort((a, b) => a - b);

    const basename = path.basename(relSrc, path.extname(relSrc));
    const variants = [];

    for (const width of widths) {
      const filename = `${basename}-${width}.webp`;
      const outputFile = path.join(outputDir, filename);
      const result = await sharp(inputFile)
        .resize({ width, withoutEnlargement: true })
        .webp({ quality: 78, effort: 4 })
        .toFile(outputFile);

      variants.push({
        src: `assets/generated/${filename}`,
        width: result.width,
        height: result.height,
      });
    }

    const fallback = variants[variants.length - 1];
    manifest[relSrc] = {
      src: fallback.src,
      srcset: variants.map(v => `${v.src} ${v.width}w`).join(', '),
      width: metadata.width,
      height: metadata.height,
    };
  }

  const contents =
    `// Generated by tools/build-images.mjs — do not edit by hand.\n` +
    `const IMAGE_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`;

  await writeFile(manifestFile, contents);
  console.log(`Generated responsive variants for ${allImages.size} images.`);
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
